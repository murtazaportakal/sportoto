const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {ChronologicalModel}=require('./ml/chronological_model');
const {summarize,pairedInterval,temperature}=require('./ml/evaluation_metrics');
const {prepare,finalEvaluation}=require('./chronological_evaluation');
const matches=require('./data/historical_matches.json').matches;
const replay=ChronologicalModel.replay(matches);
assert.ok(replay.rows.length>100);
assert.ok(replay.rows.every(r=>r.latestInputDate<r.date));
assert.deepEqual(ChronologicalModel.replay([...matches].reverse()),replay,'Input ordering cannot affect replay');
const cutoff='2025-01-01';
const changed=matches.map(m=>m.date>=cutoff?{...m,homeGoals:20,awayGoals:0,actualOutcome:'1'}:m);
assert.deepEqual(ChronologicalModel.replay(changed).rows.filter(r=>r.date<=cutoff),replay.rows.filter(r=>r.date<=cutoff),'Same-day/future scores cannot affect earlier probabilities');
const context=vm.createContext({matches});
vm.runInContext(fs.readFileSync('ml/chronological_model.js','utf8'),context);
assert.equal(vm.runInContext('JSON.stringify(ChronologicalModel.replay(matches))',context),JSON.stringify(replay));
const perfect=summarize(['1','X','2'].map((actualOutcome,i)=>({actualOutcome,probabilities:[0,0,0].map((_,j)=>Number(i===j))})));
assert.equal(perfect.logLoss,0);assert.equal(perfect.brierScore,0);assert.equal(perfect.accuracy,1);assert.equal(perfect.calibrationError,0);
const uniform=summarize([{actualOutcome:'1',probabilities:[1/3,1/3,1/3]}]);
assert.ok(Math.abs(uniform.logLoss-Math.log(3))<1e-12);assert.ok(Math.abs(uniform.brierScore-2/3)<1e-12);
assert.equal(summarize([]).logLoss,null);assert.throws(()=>summarize([{actualOutcome:'1',probabilities:[1,1,1]}]));
assert.deepEqual(temperature([.2,.3,.5],1).map(v=>Number(v.toFixed(9))),[.2,.3,.5]);
const rows=replay.rows.slice(0,40),interval=pairedInterval(rows,'uniform',{iterations:100});
assert.deepEqual(pairedInterval(rows,'uniform',{iterations:100}),interval);
assert.ok(interval.lower<=interval.upper);
assert.equal(pairedInterval(rows.map(r=>({...r,group:'one'})),'uniform').lower,null);
const protocol=prepare(matches),testChanged=matches.map(m=>m.date>protocol.split.validationEnd?{...m,homeGoals:20,awayGoals:0,actualOutcome:'1'}:m);
const changedProtocol=prepare(testChanged);
assert.deepEqual(changedProtocol.params,protocol.params);assert.deepEqual(changedProtocol.calibrator,protocol.calibrator);assert.deepEqual(changedProtocol.validation,protocol.validation);
const synthetic=Array.from({length:60},(_,i)=>({date:new Date(Date.UTC(2030,7,i+1)).toISOString().slice(0,10),homeCode:i%2?'A':'B',awayCode:i%2?'B':'A',homeGoals:i%3,awayGoals:1,actualOutcome:i%3===0?'2':i%3===1?'X':'1',round:'Week '+Math.floor(i/7)}));
const syntheticProtocol=prepare(synthetic),final=finalEvaluation(synthetic,syntheticProtocol);
assert.ok(final.eligibleTest>0);assert.equal(final.release.eligible,false);
assert.throws(()=>finalEvaluation(testChanged,syntheticProtocol),/Frozen dataset changed/);
assert.throws(()=>ChronologicalModel.replay([...matches,matches[0]]),/Duplicate/);
const {walkForward}=require('./walk_forward_evaluation');
const folds=walkForward(matches,protocol.split.developmentEnd);
assert.deepEqual(walkForward(testChanged,protocol.split.developmentEnd),folds);
assert.ok(folds.folds.every(f=>f.trainEnd<f.testStart&&f.testStart<=f.testEnd));
const firstEnd=folds.folds[0].testEnd;
const futureChanged=matches.map(m=>m.date>firstEnd?{...m,homeGoals:20,awayGoals:0,actualOutcome:'1'}:m);
assert.deepEqual(walkForward(futureChanged,protocol.split.developmentEnd).folds[0],folds.folds[0]);
console.log('Passed: chronological cutoffs, same-day exclusion, shuffle/browser parity, untouched selection, calibration math and seeded cluster intervals.');
